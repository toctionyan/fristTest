#!/usr/bin/env python3
"""Bind the exact validated Git tree to a Stage-3 candidate plan.

Before the tree becomes immutable, this trusted controller also closes deterministic
product-source dependencies such as the protected source baseline. Model/fixer output
remains limited to Stage-2 source paths; derived authority files are regenerated by
control-plane code and recorded separately.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Any

from refresh_product_source_baseline import (
    BaselineRefreshError,
    refresh_product_source_baseline,
)


class TreeBindingError(RuntimeError):
    pass


def _load(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise TreeBindingError(f"JSON object required: {path}")
    return payload


def _git(workspace: Path, *args: str) -> str:
    completed = subprocess.run(
        ["git", *args],
        cwd=workspace,
        text=True,
        capture_output=True,
        check=False,
        timeout=120,
    )
    if completed.returncode:
        raise TreeBindingError((completed.stderr or completed.stdout or "git failed").strip())
    return completed.stdout.strip()


def _status_paths(workspace: Path) -> list[str]:
    rows = _git(workspace, "status", "--porcelain=v1", "--untracked-files=all").splitlines()
    paths: list[str] = []
    for row in rows:
        raw = row[3:] if len(row) > 3 else ""
        path = raw.split(" -> ")[-1].strip().replace("\\", "/")
        if path and path not in paths:
            paths.append(path)
    return paths


def _close_derived_authorities(workspace: Path, plan: dict[str, Any]) -> list[str]:
    source_sha = str(plan.get("head_sha") or "")
    try:
        baseline = refresh_product_source_baseline(
            workspace,
            generated_from_sha=source_sha,
            allow_missing=True,
        )
    except BaselineRefreshError as exc:
        raise TreeBindingError(str(exc)) from exc
    derived: list[str] = []
    if baseline.get("changed") is True and baseline.get("path"):
        derived.append(str(baseline["path"]))
    return derived


def _publish_candidate_sha_to_current_step(candidate_sha: str) -> None:
    """Override the pre-closure candidate_sha emitted earlier in the same Actions step."""
    output = str(os.getenv("GITHUB_OUTPUT") or "").strip()
    if not output:
        return
    path = Path(output)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(f"candidate_sha={candidate_sha}\n")


def bind_tree(*, workspace: Path, plan_path: Path) -> dict[str, Any]:
    workspace = workspace.resolve()
    plan = _load(plan_path)
    if plan.get("schema") != "github-governed-repair-stage3@1":
        raise TreeBindingError("unsupported Stage-3 plan schema")
    if plan.get("status") != "CANDIDATE_PREPARED":
        raise TreeBindingError("Stage-3 candidate is not prepared")
    head = _git(workspace, "rev-parse", "HEAD")
    if head != str(plan.get("candidate_sha") or ""):
        raise TreeBindingError("Stage-3 candidate SHA drifted before tree binding")
    if _status_paths(workspace):
        raise TreeBindingError("Stage-3 candidate workspace is dirty before dependency closure")
    parent = _git(workspace, "rev-parse", "HEAD^")
    if parent != str(plan.get("head_sha") or ""):
        raise TreeBindingError("Stage-3 candidate parent is not the failed source SHA")

    source_paths = [str(item) for item in plan.get("changed_paths") or []]
    derived_paths = _close_derived_authorities(workspace, plan)
    if derived_paths:
        actual = _status_paths(workspace)
        if actual != derived_paths:
            raise TreeBindingError(
                f"derived authority closure changed unexpected paths: expected={derived_paths} actual={actual}"
            )
        _git(workspace, "add", "--", *derived_paths)
        _git(workspace, "commit", "--amend", "--no-edit")
        head = _git(workspace, "rev-parse", "HEAD")
        plan["candidate_sha"] = head

    if _status_paths(workspace):
        raise TreeBindingError("Stage-3 candidate workspace is dirty before tree binding")
    parent = _git(workspace, "rev-parse", "HEAD^")
    if parent != str(plan.get("head_sha") or ""):
        raise TreeBindingError("derived authority amendment changed the candidate parent")
    tree = _git(workspace, "rev-parse", "HEAD^{tree}")
    if len(tree) != 40:
        raise TreeBindingError("invalid validated Git tree identity")

    publication_paths = list(source_paths)
    for path in derived_paths:
        if path not in publication_paths:
            publication_paths.append(path)
    plan["derived_paths"] = derived_paths
    plan["publication_paths"] = publication_paths
    plan["validated_tree_sha"] = tree
    plan["validated_parent_sha"] = parent
    plan["tree_binding_complete"] = True
    plan["full_validation_passed"] = False
    plan["draft_pr_published"] = False
    plan["production_closed"] = False
    plan_path.write_text(
        json.dumps(plan, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return plan


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", required=True)
    parser.add_argument("--plan", required=True)
    args = parser.parse_args()
    try:
        plan = bind_tree(workspace=Path(args.workspace), plan_path=Path(args.plan))
        _publish_candidate_sha_to_current_step(str(plan.get("candidate_sha") or ""))
    except (OSError, json.JSONDecodeError, subprocess.SubprocessError, TreeBindingError) as exc:
        print(json.dumps({"status": "BLOCKED", "error": str(exc)}), file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
